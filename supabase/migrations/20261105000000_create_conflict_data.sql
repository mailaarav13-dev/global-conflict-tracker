create table if not exists public.conflicts (
  id text primary key,
  title text not null,
  region text not null check (region in (
    'North America',
    'South America',
    'Europe',
    'Middle East & North Africa',
    'Sub-Saharan Africa',
    'Asia-Pacific'
  )),
  conflict_type text not null check (conflict_type in (
    'Interstate War',
    'Civil War',
    'Transnational Terrorism',
    'Political Instability'
  )),
  status text not null check (status in ('Deteriorating', 'Constant', 'Improving')),
  impact_level text not null check (impact_level in ('High', 'Medium', 'Low')),
  scope text not null check (scope in ('International', 'Internal', 'Transnational')),
  iso_countries text[] not null,
  center_latitude double precision not null check (center_latitude between -90 and 90),
  center_longitude double precision not null check (center_longitude between -180 and 180),
  summary text not null,
  historical_context text not null,
  strategic_impact text not null,
  source_links text[] not null default '{}',
  editorial_updated_at date,
  snapshot_updated_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create table if not exists public.conflict_news (
  id bigint generated by default as identity primary key,
  conflict_id text not null references public.conflicts(id) on delete cascade,
  url text not null,
  title text not null,
  source text not null,
  published_at timestamptz,
  provider text not null,
  sample boolean not null default false,
  snapshot_updated_at timestamptz not null default now()
);

create table if not exists public.data_refresh_runs (
  id bigint generated by default as identity primary key,
  provider text not null,
  status text not null check (status in ('succeeded', 'failed')),
  conflict_count integer not null default 0,
  news_item_count integer not null default 0,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists conflict_news_published_at_idx
  on public.conflict_news (published_at desc);

alter table public.conflicts enable row level security;
alter table public.conflict_news enable row level security;
alter table public.data_refresh_runs enable row level security;

drop policy if exists "Public conflicts are readable" on public.conflicts;
create policy "Public conflicts are readable"
  on public.conflicts for select
  to anon, authenticated
  using (true);

drop policy if exists "Public conflict news is readable" on public.conflict_news;
create policy "Public conflict news is readable"
  on public.conflict_news for select
  to anon, authenticated
  using (true);

create or replace function public.replace_conflict_snapshot(
  p_conflicts jsonb,
  p_news jsonb,
  p_metadata jsonb default '{}'::jsonb
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  conflict_record jsonb;
  news_record jsonb;
begin
  if jsonb_typeof(p_conflicts) <> 'array' or jsonb_typeof(p_news) <> 'array' then
    raise exception 'Snapshot payloads must be JSON arrays';
  end if;

  for conflict_record in select value from jsonb_array_elements(p_conflicts)
  loop
    insert into public.conflicts (
      id,
      title,
      region,
      conflict_type,
      status,
      impact_level,
      scope,
      iso_countries,
      center_latitude,
      center_longitude,
      summary,
      historical_context,
      strategic_impact,
      source_links,
      editorial_updated_at,
      snapshot_updated_at
    )
    values (
      conflict_record->>'id',
      conflict_record->>'title',
      conflict_record->>'region',
      conflict_record->>'type',
      conflict_record->>'status',
      conflict_record->>'impact_level',
      conflict_record->>'scope',
      array(select jsonb_array_elements_text(conflict_record->'iso_countries')),
      (conflict_record->'center_coordinates'->>'latitude')::double precision,
      (conflict_record->'center_coordinates'->>'longitude')::double precision,
      conflict_record->>'summary',
      conflict_record->>'historical_context',
      conflict_record->>'strategic_impact',
      coalesce(array(select jsonb_array_elements_text(conflict_record->'source_links')), '{}'),
      nullif(conflict_record->>'updated_at', '')::date,
      now()
    )
    on conflict (id) do update set
      title = excluded.title,
      region = excluded.region,
      conflict_type = excluded.conflict_type,
      status = excluded.status,
      impact_level = excluded.impact_level,
      scope = excluded.scope,
      iso_countries = excluded.iso_countries,
      center_latitude = excluded.center_latitude,
      center_longitude = excluded.center_longitude,
      summary = excluded.summary,
      historical_context = excluded.historical_context,
      strategic_impact = excluded.strategic_impact,
      source_links = excluded.source_links,
      editorial_updated_at = excluded.editorial_updated_at,
      snapshot_updated_at = excluded.snapshot_updated_at;
  end loop;

  delete from public.conflicts
  where not exists (
    select 1
    from jsonb_array_elements(p_conflicts) as item(value)
    where item.value->>'id' = public.conflicts.id
  );

  delete from public.conflict_news;

  for news_record in select value from jsonb_array_elements(p_news)
  loop
    insert into public.conflict_news (
      conflict_id,
      url,
      title,
      source,
      published_at,
      provider,
      sample,
      snapshot_updated_at
    )
    values (
      news_record->>'conflict_id',
      news_record->>'url',
      news_record->>'title',
      news_record->>'source',
      nullif(news_record->>'published_at', '')::timestamptz,
      news_record->>'provider',
      coalesce((news_record->>'sample')::boolean, false),
      now()
    );
  end loop;

  insert into public.data_refresh_runs (
    provider,
    status,
    conflict_count,
    news_item_count,
    metadata
  )
  values (
    coalesce(p_metadata->>'news_provider', 'unknown'),
    'succeeded',
    jsonb_array_length(p_conflicts),
    jsonb_array_length(p_news),
    p_metadata
  );
end;
$$;

revoke all on function public.replace_conflict_snapshot(jsonb, jsonb, jsonb) from public;
revoke all on function public.replace_conflict_snapshot(jsonb, jsonb, jsonb) from anon;
revoke all on function public.replace_conflict_snapshot(jsonb, jsonb, jsonb) from authenticated;
grant execute on function public.replace_conflict_snapshot(jsonb, jsonb, jsonb) to service_role;
